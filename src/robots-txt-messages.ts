export function warningText(w: Robots["warnings"][number], locale: Locale): string {
  return ROBOTS_WARNINGS[w.code][locale].replace("{field}", w.field ?? "");
}

export function reasonText(d: Decision, locale: Locale): string {
  return ROBOTS_REASONS[d.reason][locale]
    .replace("{line}", String(d.rule?.line ?? ""))
    .replace("{pattern}", d.rule?.pattern ?? "");
}
