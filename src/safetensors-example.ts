export type ExampleFile = { name: string; size: number; header: Uint8Array };

function header(list: [string, number[]][]): Uint8Array {
  let off = 0;
  let s = '{"__metadata__":{"format":"pt"}';
  for (const [name, shape] of list) {
    const n = shape.reduce((a, d) => a * d, 1) * 2;
    s += `,${JSON.stringify(name)}:{"dtype":"BF16","shape":[${shape.join(",")}],"data_offsets":[${off},${off + n}]}`;
    off += n;
  }
  s += "}";
  s += " ".repeat((8 - (s.length % 8)) % 8);
  const h = new TextEncoder().encode(s);
  const out = new Uint8Array(8 + h.length);
  new DataView(out.buffer).setBigUint64(0, BigInt(h.length), true);
  out.set(h, 8);
  return out;
}

