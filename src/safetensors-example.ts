export function buildExampleFiles(): ExampleFile[] {
  return TENSORS.map((list, i) => {
    const name = `model-0000${i + 1}-of-00004.safetensors`;
    return { name, size: FILE_SIZES[i], header: header(list) };
  });
}

/** transformers と同じ書き方(json.dumps(indent=2, sort_keys=True) + 改行)の index.json。 */
export function buildExampleIndex(): string {
  const map: Record<string, string> = {};
  let total = 0;
  TENSORS.forEach((list, i) => {
    for (const [name, shape] of list) {
      map[name] = `model-0000${i + 1}-of-00004.safetensors`;
      total += shape.reduce((a, d) => a * d, 1) * 2;
    }
  });
  const keys = Object.keys(map).sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));
  const lines = keys.map((k) => `    ${JSON.stringify(k)}: ${JSON.stringify(map[k])}`);
  return `{\n  "metadata": {\n    "total_size": ${total}\n  },\n  "weight_map": {\n${lines.join(",\n")}\n  }\n}\n`;
}
