/** 例の見出しのバイト列と、ファイルがあるべき大きさ(見出し+重み)を返す。 */
export function buildExample(): { bytes: Uint8Array; size: number } {
  const parts: number[] = [];
  const dv = new DataView(new ArrayBuffer(8));
  const push = (n: number) => {
    for (let i = 0; i < n; i++) parts.push(dv.getUint8(i));
  };
  const u32 = (n: number) => {
    dv.setUint32(0, n, true);
    push(4);
  };
  const u64 = (n: number) => {
    dv.setBigUint64(0, BigInt(n), true);
    push(8);
  };
  const str = (s: string) => {
    const e = new TextEncoder().encode(s);
    u64(e.length);
    for (const x of e) parts.push(x);
  };
  const val = (t: ValueType, v: Scalar) => {
    if (t === "string") str(v as string);
    else if (t === "uint32") u32(v as number);
    else if (t === "int32") {
      dv.setInt32(0, v as number, true);
      push(4);
    } else if (t === "float32") {
      dv.setFloat32(0, v as number, true);
      push(4);
    } else if (t === "bool") parts.push(v ? 1 : 0);
    else if (t === "uint64") u64(v as number);
    else throw new Error(t);
  };
  for (const c of "GGUF") parts.push(c.charCodeAt(0));
  u32(3);
  u64(TENSORS.length);
  u64(META.length);
  for (const [key, type, value, item] of META) {
    str(key);
    u32(VALUE_TYPES.indexOf(type));
    if (type === "array") {
      const arr = value as Scalar[];
      u32(VALUE_TYPES.indexOf(item!));
      u64(arr.length);
      for (const x of arr) val(item!, x);
    } else val(type, value as Scalar);
  }
  const align = (x: number) => x + ((32 - (x % 32)) % 32);
  let offset = 0;
  for (const [name, shape, type] of TENSORS) {
    str(name);
    u32(shape.length);
    for (const d of shape) u64(d);
    u32(type);
    u64(offset);
    const [, block, bytes] = GGML_TYPES[type];
    offset += align((shape.reduce((a, b) => a * b, 1) / block) * bytes);
  }
  return { bytes: Uint8Array.from(parts), size: align(parts.length) + offset };
}
